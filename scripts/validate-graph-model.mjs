#!/usr/bin/env node
/**
 * Validates docs/model/graph-model.json against the real Neo4j `mcp-neo4j-data-modeling` MCP server
 * (WO-022, ADR-002 tarea "Validar el modelo multi-proyecto con neo4j-data-modeling").
 *
 * Usage:
 *   node scripts/validate-graph-model.mjs
 *
 * Requires `uvx` (uv 0.12.13+) on PATH or at ~/.local/bin/uvx; spawns
 * `uvx mcp-neo4j-data-modeling@0.8.2 --transport stdio` as a child process (no network Neo4j connection
 * needed -- this server only validates/transforms an in-memory data model, it never talks to a database).
 *
 * What this script does:
 *   1. Reads docs/model/graph-model.json and strips the `x-prdm` extension key, since the MCP server's
 *      DataModel schema only supports {nodes, relationships, metadata}. The full file (including x-prdm)
 *      remains the source of truth committed to the repo.
 *   2. Lists the server's tools (logged, so this script also documents the exact tool surface used).
 *   3. Calls `validate_node` for every node and `validate_relationship` for every relationship
 *      individually (precise per-element error messages), then `validate_data_model` on the whole model
 *      (catches cross-element issues: relationships pointing at undeclared labels, duplicate labels, etc).
 *   4. Calls `get_constraints_cypher_queries` for visibility/comparison and logs its output, but does NOT
 *      use it to generate docs/model/graph-model.cypher: this MCP server's Node.key_property supports only
 *      a single property, so it cannot express this schema's composite (project_id, id|key|sha) uniqueness
 *      constraints -- its Cypher would create incorrect *bare* uniqueness constraints. Instead
 *      graph-model.cypher is generated straight from the authoritative `x-prdm.constraints`/`x-prdm.indexes`
 *      sections of graph-model.json, which mirror packages/core/src/graph/migrations.ts exactly.
 *   5. Calls `export_to_arrows_json` and `get_mermaid_config_str` for visibility (logged only, not written
 *      to disk, to keep this WO's file ownership scoped to graph-model.json/.cypher).
 *   6. Exits non-zero (after printing every collected error) if any validation call fails.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const MODEL_PATH = path.join(REPO_ROOT, 'docs', 'model', 'graph-model.json');
const CYPHER_PATH = path.join(REPO_ROOT, 'docs', 'model', 'graph-model.cypher');
const UVX = process.env.UVX_BIN ?? 'uvx';
const SERVER_SPEC = 'mcp-neo4j-data-modeling@0.8.2';

/** Throws with every failing tool call's error text collected, instead of stopping at the first one. */
class ValidationFailure extends Error {
  constructor(failures) {
    super(`graph-model.json failed ${failures.length} validation check(s):\n${failures.map((f) => `  - ${f}`).join('\n')}`);
    this.failures = failures;
  }
}

function toolResultText(result) {
  return result.content?.map((c) => (c.type === 'text' ? c.text : `[${c.type}]`)).join('\n') ?? '';
}

async function callTool(client, name, args, failures, label) {
  const result = await client.callTool({ name, arguments: args });
  const text = toolResultText(result);
  if (result.isError) {
    failures.push(`${label}: ${text}`);
    console.error(`FAIL ${label}\n${text}`);
  } else {
    console.log(`ok   ${label}`);
  }
  return { result, text };
}

function dataModelOf(doc) {
  const { nodes, relationships, metadata } = doc;
  return { nodes, relationships, metadata: metadata ?? {} };
}

/** Renders graph-model.cypher straight from the authoritative x-prdm sections (see header comment for why). */
function renderCypher(doc) {
  const { schemaVersion } = doc.metadata;
  const { constraints, indexes, migrations } = doc['x-prdm'];
  const lines = [
    '// Generated by scripts/validate-graph-model.mjs from docs/model/graph-model.json (x-prdm.constraints/x-prdm.indexes).',
    '// This is the authoritative DDL for the schema (mirrors packages/core/src/graph/migrations.ts exactly);',
    '// it is NOT the output of mcp-neo4j-data-modeling get_constraints_cypher_queries, which cannot express',
    '// this schema\'s composite (project_id, <key>) uniqueness constraints (see x-prdm.compositeKeyLimitation).',
    `// Schema version: ${schemaVersion} (migrations: ${migrations.map((m) => `${m.version}:${m.name}`).join(', ')})`,
    '',
    '// -- Constraints ---------------------------------------------------------------------------',
    '',
  ];
  for (const c of constraints) {
    const props = c.properties.length === 1 ? `n.${c.properties[0]}` : `(${c.properties.map((p) => `n.${p}`).join(', ')})`;
    lines.push(`CREATE CONSTRAINT ${c.name} IF NOT EXISTS FOR (n:${c.label}) REQUIRE ${props} IS UNIQUE;`);
  }
  lines.push('', '// -- Indexes --------------------------------------------------------------------------------', '');
  for (const i of indexes) {
    if (i.type === 'RANGE') {
      const props = i.properties.map((p) => `n.${p}`).join(', ');
      lines.push(`CREATE INDEX ${i.name} IF NOT EXISTS FOR (n:${i.label}) ON (${props});`);
    } else if (i.type === 'FULLTEXT') {
      const props = i.properties.map((p) => `n.${p}`).join(', ');
      lines.push(`CREATE FULLTEXT INDEX ${i.name} IF NOT EXISTS FOR (n:${i.label}) ON EACH [${props}]; // analyzer: ${i.analyzer} (${i.analyzerNote})`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const raw = await readFile(MODEL_PATH, 'utf8');
  const doc = JSON.parse(raw);
  const dataModel = dataModelOf(doc);
  const failures = [];

  const transport = new StdioClientTransport({ command: UVX, args: [SERVER_SPEC, '--transport', 'stdio'] });
  const client = new Client({ name: 'prdm-graph-model-validator', version: '1.0.0' });
  await client.connect(transport);

  try {
    const { tools } = await client.listTools();
    console.log(`connected to ${SERVER_SPEC}; ${tools.length} tools available: ${tools.map((t) => t.name).join(', ')}`);

    for (const node of dataModel.nodes) {
      await callTool(client, 'validate_node', { node, return_validated: false }, failures, `validate_node(${node.label})`);
    }
    for (const rel of dataModel.relationships) {
      await callTool(
        client,
        'validate_relationship',
        { relationship: rel, return_validated: false },
        failures,
        `validate_relationship(${rel.type}: ${rel.start_node_label}->${rel.end_node_label})`,
      );
    }
    const { text: modelResultText } = await callTool(client, 'validate_data_model', { data_model: dataModel, return_validated: false }, failures, 'validate_data_model(full model)');
    console.log(`validate_data_model result: ${modelResultText}`);

    // Informational-only exports (see header comment): logged, not written to disk.
    const constraintsPreview = await client.callTool({ name: 'get_constraints_cypher_queries', arguments: { data_model: dataModel } });
    console.log('\n--- get_constraints_cypher_queries (informational; NOT used for graph-model.cypher, see header) ---');
    console.log(toolResultText(constraintsPreview));

    const mermaid = await client.callTool({ name: 'get_mermaid_config_str', arguments: { data_model: dataModel } });
    console.log(`\nget_mermaid_config_str: ${toolResultText(mermaid).length} chars (not written to disk)`);

    const arrows = await client.callTool({ name: 'export_to_arrows_json', arguments: { data_model: dataModel } });
    console.log(`export_to_arrows_json: ${toolResultText(arrows).length} chars (not written to disk)`);

    if (failures.length > 0) throw new ValidationFailure(failures);

    const cypher = renderCypher(doc);
    await writeFile(CYPHER_PATH, cypher, 'utf8');
    console.log(`\nwrote ${path.relative(REPO_ROOT, CYPHER_PATH)}`);
    console.log('\ngraph-model.json is valid.');
  } finally {
    await client.close();
  }
}

main().catch((err) => {
  console.error(err instanceof ValidationFailure ? err.message : err.stack ?? String(err));
  process.exitCode = 1;
});
